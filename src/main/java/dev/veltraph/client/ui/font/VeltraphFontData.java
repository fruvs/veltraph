    /**
     * Decode the packed stream into one coverage value (0..15) per pixel, row-major per glyph:
     * {@code [GLYPH_COUNT * GLYPH_W * GLYPH_H]}.
     */
    static byte[] decode() {
        byte[] out = new byte[NIBBLE_COUNT];
        for (int i = 0; i < NIBBLE_COUNT; i++) {
            int bytePos = i >> 1;
            int hi = Character.digit(HEX.charAt(bytePos * 2), 16);
            int lo = Character.digit(HEX.charAt(bytePos * 2 + 1), 16);
            int b = (hi << 4) | lo;
            out[i] = (byte) ((i & 1) == 0 ? (b >> 4) & 0xF : b & 0xF);
        }
        return out;
    }
