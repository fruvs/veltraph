package dev.veltraph.client.rewarp;
/** A manual takeover retires only the old issued helper, before ordinary Root dispatch resumes. */
public final class GeorgeManualCustody {
    private GeorgeManualCustody(){}
    public static boolean mayContinue(Object helper,Object token,Object permit,boolean enabled,Object currentOwner,Object currentToken,Object currentPermit){return helper!=null&&token!=null&&permit!=null&&enabled&&currentOwner==helper&&currentToken==token&&currentPermit==permit;}
}
